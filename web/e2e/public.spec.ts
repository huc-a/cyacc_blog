test('whole cards open details from cover, summary, footer and keyboard', async ({ page }) => {
  await page.setViewportSize({ width: 1104, height: 828 })
  const card = page.locator('.content-card').filter({ has: page.getByRole('heading', { name: `阅读验证 ${token}`, exact: true }) })
  await page.goto('/')
  await expect(card.locator('a')).toHaveCount(1)
  await expect(card.locator('.card-meta')).toHaveCSS('background-color', 'rgb(248, 245, 233)')
  await expect(card.locator('.card-meta')).toContainText('文章')
  await expect(card.locator('.card-meta .card-tag')).toHaveText(`#${token}`)
  const cover = await card.locator('.card-cover').boundingBox(), copy = await card.locator('.card-inner').boundingBox()
  expect(cover!.y).toBeLessThan(copy!.y)
  expect(cover!.y + cover!.height).toBeGreaterThanOrEqual(copy!.y + copy!.height - 1)
  for (const target of ['.card-visual', '.card-inner p', '.card-meta']) {
    await page.goto('/')
    // Cover's upper empty area is deliberately clickable too.
    await card.locator(target).click(target === '.card-visual' ? { position: { x: 15, y: 15 } } : {})
    await expect(page).toHaveURL(`/articles/${token}`)
    await expect(page.locator('.prose')).toContainText('这是公开正文')
  }
  await page.goto('/articles')
  await card.getByRole('link').focus(); await page.keyboard.press('Enter')
  await expect(page).toHaveURL(`/articles/${token}`)
})

test('collection search expands inline, filters locally, and clears on mobile', async ({ page }) => {
  for (const width of [1104, 390]) {
    await page.setViewportSize({ width, height: 828 }); await page.goto('/articles')
    const search = page.getByRole('search', { name: '文章内搜索' })
    const input = search.getByRole('searchbox', { name: '搜索文章' })
    await expect(input).toHaveCount(0)
    await search.getByRole('button', { name: '搜索', exact: true }).click()
    await expect(input).toBeFocused()
    await input.fill(token); await input.press('Enter')
    await expect(page).toHaveURL(`/articles?q=${token}`)
    await expect(page.locator('.collection-grid .content-card')).toHaveCount(1)
    await expect(page.locator('.collection-grid')).toContainText(`阅读验证 ${token}`)
    await input.press('Escape'); await expect(input).toHaveCount(0)
    await expect(page.locator('.collection-search-state')).toContainText(token)
    await page.getByRole('button', { name: '清除搜索' }).click()
    await expect(page).toHaveURL('/articles')
    await search.getByRole('button', { name: '搜索', exact: true }).click()
    await input.fill('不会匹配的搜索词'); await search.getByRole('button', { name: '提交搜索' }).click()
    await expect(page.locator('.collection-grid .content-card')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await page.getByRole('button', { name: '清除搜索' }).click()
    await page.screenshot({ path: `test-results/collection-inline-search-${width}.png`, animations: 'disabled' })
  }
})

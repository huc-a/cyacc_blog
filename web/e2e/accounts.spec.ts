import { test, expect } from '@playwright/test'
import { login, mutate } from './helpers'

test('accounts: create, equal permissions, reset password, suspend, re-enable and mobile layout', async ({ page, request, playwright, baseURL }) => {
  const username = `e2e-account-${Date.now()}`, initial = `Initial-${Date.now()}-secret`, next = `Updated-${Date.now()}-secret`
  const peer = await playwright.request.newContext({ baseURL })
  let created: { id: number; enabled: boolean; lockVersion: number } | undefined
  async function peerLogin(password: string) {
    const csrf = await (await peer.get('/api/auth/csrf')).json()
    return peer.post('/api/auth/login', { form: { username, password }, headers: { [csrf.headerName]: csrf.token } })
  }
  await login(request)
  await login(page.request)
  await page.goto('/admin/dashboard')
  await page.getByRole('link', { name: '账号管理', exact: false }).click()
  const row = page.getByRole('row').filter({ hasText: username })
  try {
    await page.getByRole('button', { name: '添加账号' }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('账号', { exact: true }).fill(username)
    await dialog.getByLabel('显示名', { exact: true }).fill('测试管理员')
    await dialog.getByLabel('初始密码', { exact: true }).fill(initial)
    await dialog.getByLabel('确认密码', { exact: true }).fill(initial)
    await dialog.getByRole('button', { name: '添加账号', exact: true }).click()
    await expect(dialog).toBeHidden(); await expect(row).toContainText('已启用')
    created = (await (await request.get('/api/admin/accounts?size=50')).json()).items.find((x: { username: string }) => x.username === username)
    expect((await peerLogin(initial)).ok()).toBeTruthy()
    expect((await peer.get('/api/admin/accounts')).ok()).toBeTruthy()
    expect((await peer.get('/api/admin/site')).ok()).toBeTruthy()
    await row.getByRole('button', { name: '重置密码' }).click()
    await dialog.getByLabel('新密码', { exact: true }).fill(next)
    await dialog.getByLabel('确认密码', { exact: true }).fill('Mismatch-test-secret')
    await dialog.getByRole('button', { name: '确认重置密码' }).click()
    await expect(dialog.getByRole('alert')).toHaveText('两次输入的密码不一致')
    await dialog.getByLabel('确认密码', { exact: true }).fill(next)
    await dialog.getByRole('button', { name: '确认重置密码' }).click()
    await expect(dialog).toBeHidden()
    expect((await peer.get('/api/admin/accounts')).status()).toBe(401)
    expect((await peerLogin(next)).ok()).toBeTruthy()
    await row.getByRole('button', { name: '停用', exact: true }).click()
    await page.getByRole('button', { name: '确认', exact: true }).click()
    await expect(row).toContainText('已停用')
    expect((await peer.get('/api/admin/accounts')).status()).toBe(401)
    await row.getByRole('button', { name: '启用', exact: true }).click()
    await page.getByRole('button', { name: '确认', exact: true }).click()
    await expect(row).toContainText('已启用')
    expect((await peerLogin(next)).ok()).toBeTruthy()
    await expect(page.locator('.n-message')).toHaveCount(0)
    await page.screenshot({ path: 'test-results/accounts-desktop.png', fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(async () => { const box = await page.locator('.admin-sidebar').boundingBox(); return box ? box.x + box.width : 0 }).toBeLessThanOrEqual(0)
    await expect(row.getByRole('button', { name: '停用', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.screenshot({ path: 'test-results/accounts-mobile.png', fullPage: true })
    await page.getByRole('button', { name: '添加账号' }).click()
    await expect(dialog.getByLabel('初始密码', { exact: true })).toHaveValue('')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.keyboard.press('Escape')
  } finally {
    const all = await (await request.get('/api/admin/accounts?size=50')).json()
    created = all.items?.find((x: { username: string }) => x.username === username)
    if (created?.enabled) await mutate(request, 'PUT', `/api/admin/accounts/${created.id}/state`, { enabled: false, lockVersion: created.lockVersion })
    await peer.dispose()
  }
})
